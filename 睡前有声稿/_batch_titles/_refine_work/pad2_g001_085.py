def main():
    done, miss = 0, []
    for p in sorted(glob.glob(os.path.join(OUT, "G*.md"))):
        gid = os.path.basename(p)[:4]
        if gid not in PAD2:
            continue
        anchor, ins = PAD2[gid]
        t = open(p, encoding="utf-8").read()
        if anchor not in t:
            miss.append(gid)
            continue
        t = t.replace(anchor, ins + "\n" + anchor, 1)
        open(p, "w", encoding="utf-8").write(t)
        done += 1
    print("padded2:", done, "anchor-miss:", miss)
    low = []
    hs = []
    for p in sorted(glob.glob(os.path.join(OUT, "G*.md"))):
        t = open(p, encoding="utf-8").read()
        body = t.split("估时：约8分钟", 1)[1]
        han = len(re.findall(r"[\u4e00-\u9fff]", body))
        hs.append(han)
        if han < 350 or han > 560:
            low.append((os.path.basename(p), han))
    print("汉字数不在350-560的:", low if low else "无")
    print("最小/最大:", min(hs), max(hs))

if __name__ == "__main__":
    main()
