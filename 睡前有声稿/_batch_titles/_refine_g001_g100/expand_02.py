def han(s):
    return len(re.findall(r"[\u4e00-\u9fff]", s))

def expand_file(path, extra):
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    idx = 0
    for i, ln in enumerate(lines):
        if ln.startswith("估时"):
            idx = i + 1
            break
    while idx < len(lines) and lines[idx].strip() == "":
        idx += 1
    body = "\n".join(lines[idx:]).strip()
    meta = "\n".join(lines[:idx]).rstrip()
    if extra.strip()[:20] in body:
        return han(body), "skip"
    new_body = body + "\n\n" + extra.strip()
    path.write_text(meta + "\n\n" + new_body + "\n", encoding="utf-8")
    return han(new_body), "ok"

def main():
    with open("/Users/song/EyeHaven/睡前有声稿/_batch_titles/knowledge.tsv") as f:
        rows = [ln.strip().split("\t") for ln in f if ln.startswith("G")]
    for gid, age, title in rows:
        n = int(gid[1:])
        if n < 51 or n > 100:
            continue
        path = ROOT / age / f"{gid}-{title}.md"
        extra = EXTRA.get(gid, "")
        if not extra:
            print("NO EXTRA", gid)
            continue
        cnt, st = expand_file(path, extra)
        print(gid, st, cnt)

if __name__ == "__main__":
    main()
