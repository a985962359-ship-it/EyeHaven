def main():
    for gid, (title, age, mins, body) in S.items():
        text = wrap(gid, title, age, mins, body)
        path = ROOT / age / f"{gid}-{title}.md"
        # remove wrong-title leftovers if any
        for old in ROOT.rglob(f"{gid}-*.md"):
            if old != path:
                old.unlink()
                print("removed", old.name)
        path.write_text(text, encoding="utf-8")
        print("wrote", path.relative_to(ROOT), len(body.strip()))


