def main() -> None:
    doc = json.loads(CATALOG.read_text(encoding="utf-8"))
    have = {s["id"] for s in doc["stories"]}
    titles = {s["title"] for s in doc["stories"]}
    added = 0
    names = {
        "cn_myth_legend": "中国神话传说（公版情节核，句子新写）",
        "cn_fable_story": "中国寓言史传（公版情节核，句子新写）",
        "foreign": "国外寓言童话（公版情节核，句子新写）",
    }
    for sid, group, title, text in STORIES:
        if title in titles and sid not in have:
            raise SystemExit(f"标题重复：{title}")
        parts = [p.strip() for p in text.split("\n") if p.strip()]
        body = "\n\n".join(parts)
        if sid not in have:
            doc["stories"].append(
                {
                    "id": sid,
                    "age": "youth",
                    "shelf": "fairy",
                    "title": title,
                    "text": body,
                    "group": group,
                }
            )
            added += 1
        md = (
            f"# {sid} {title}\n"
            f"系列：光光睡前小故事\n"
            f"年龄：13-15岁\n"
            f"来源：{names[group]}\n"
            f"估时：约8分钟\n\n"
            f"{body}\n"
        )
        (MD_DIR / f"{sid}-{title}.md").write_text(md, encoding="utf-8")
    doc["version"] = max(int(doc.get("version") or 1), 2) + 1
