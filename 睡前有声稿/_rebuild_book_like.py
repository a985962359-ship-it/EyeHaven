def load_knowledge():
    full = {}
    for line in K_FULL.read_text(encoding="utf-8").splitlines():
        p = line.split("\t")
        if len(p) >= 4:
            full[p[0]] = (p[2], p[3])
    rows = []
    for line in K_TSV.read_text(encoding="utf-8").splitlines():
        p = line.split("\t")
        if len(p) >= 3 and p[0].startswith("G"):
            n = int(p[0][1:])
            myth, truth = full.get(p[2], ("有人说错了", "要找能验证的说法"))
            rows.append((p[0], n, p[2], myth, truth))
    return rows


