def write_md(path: Path, sid: str, title: str, series: str, folder_age: str, body: str, source: str | None = None, mins: int = 8):
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"# {sid} {title}", f"系列：{series}", f"年龄：{folder_age}"]
    if source:
        lines.append(f"来源：{source}")
    lines.append(f"估时：约{mins}分钟")
    lines.append("")
    lines.append(body.strip())
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


