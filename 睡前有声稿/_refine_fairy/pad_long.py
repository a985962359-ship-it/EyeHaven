def body_len(text):
    body = text.split("\n\n", 1)[-1]
    return len(re.sub(r"\s+", "", body))

def main():
    short, long, miss = [], [], []
    for sid, pad in P.items():
        paths = list(ROOT.rglob(f"{sid}-*.md"))
        if not paths:
            miss.append(sid)
            continue
        p = paths[0]
        text = p.read_text(encoding="utf-8")
        # 若已有本轮标记则跳过，避免重复
        if "<!--pad-->" in text:
            n = body_len(text)
            (short if n < 450 else long if n > 900 else []).append((sid, n))
            continue
        lines = text.splitlines(keepends=True)
        out = []
        inserted = False
        for line in lines:
            if not inserted and (line.startswith("光光") or line.startswith("夜里，光光") or line.startswith("光光把") or line.startswith("光光讲") or line.startswith("光光轻") or line.startswith("光光说")):
                out.append("\n<!--pad-->\n" + pad + "\n\n")
                inserted = True
            out.append(line)
        if not inserted:
            out.append("\n<!--pad-->\n" + pad + "\n")
        new = "".join(out)
        # 去掉 HTML 注释以免进有声（保留内容）
        new = new.replace("<!--pad-->\n", "")
        p.write_text(new, encoding="utf-8")
        n = body_len(new)
        if n < 450:
            short.append((sid, n))
        elif n > 900:
            long.append((sid, n))
    print("miss", miss)
    print("short", short)
    print("long", long)
    # stats
    alln = []
    for p in ROOT.rglob("S*.md"):
        m = re.match(r"S(\d+)-", p.name)
        if not m: continue
        n = int(m.group(1))
        if 1 <= n <= 100:
            alln.append(body_len(p.read_text(encoding="utf-8")))
    print("count", len(alln), "min", min(alln), "max", max(alln), "avg", sum(alln)//len(alln))

if __name__ == "__main__":
    main()
