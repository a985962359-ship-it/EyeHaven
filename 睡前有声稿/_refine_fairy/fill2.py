def main():
    short, long = [], []
    for sid, fill in F.items():
        paths = list(ROOT.rglob(f"{sid}-*.md"))
        p = paths[0]
        text = p.read_text(encoding="utf-8")
        if MARK in text:
            n = len(compact(text.split("\n\n", 1)[-1]))
            if n < 450: short.append((sid, n))
            if n > 900: long.append((sid, n))
            continue
        # insert before 光光*
        lines = text.splitlines(keepends=True)
        out = []
        done = False
        for line in lines:
            if not done and (
                line.startswith("光光")
                or line.startswith("夜里，光光")
            ):
                out.append(f"\n{MARK}\n{fill}\n\n")
                done = True
            out.append(line)
        if not done:
            out.append(f"\n{MARK}\n{fill}\n")
        new = "".join(out).replace(MARK + "\n", "")
        p.write_text(new, encoding="utf-8")
        n = len(compact(new.split("\n\n", 1)[-1]))
        if n < 450:
            short.append((sid, n))
        if n > 900:
            long.append((sid, n))
