def main():
    rows = []
    for line in TSV.read_text(encoding="utf-8").splitlines():
        p = line.split("\t")
        if len(p) >= 3 and p[0].startswith("S"):
            n = int(p[0][1:])
            if 121 <= n <= 200:
                rows.append((p[0], p[1], p[2], p[3] if len(p) > 3 else "原创"))

    for i, (sid, age, title, source) in enumerate(rows):
        if sid in B:
            body = B[sid]
        else:
            body = allegory(title, sid, i)
        # ensure light length pad
        if len(body) < 280:
            body += (
                f"\n后来人们把这事讲短、讲滑。住在故事附近的孩子却记得细节："
                f"谁停过、谁问过、谁没有用嗓门赢。细节比口号耐睡。\n"
            )
        text = wrap(sid, title, age, source, body, 9 if age.startswith("6") else 10)
        out = ROOT / age / f"{sid}-{title}.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
        print("wrote", out.name)

    print("done", len(rows))


if __name__ == "__main__":
    main()
