def main() -> None:
    doc = json.loads(CATALOG.read_text(encoding="utf-8"))
    have = {s["id"] for s in doc["stories"]}
    added = 0
    MD_DIR.mkdir(parents=True, exist_ok=True)
    for sid, group, title, text in STORIES:
        text = "\n".join(line.rstrip() for line in text.strip().splitlines())
        text = text.replace("\n\n", "\n")
        # 保留段落
        parts = [p.strip() for p in text.split("\n") if p.strip()]
        body = "\n\n".join(parts)
        if sid in have:
            for s in doc["stories"]:
                if s["id"] == sid:
                    s.update(
                        age="youth",
                        shelf="fairy",
                        title=title,
                        text=body,
                        group=group,
                    )
            added += 0
        else:
            doc["stories"].append(
                {
                    "id": sid,
                    "age": "youth",
                    "shelf": "fairy",
                    "title": title,
                    "text": body,
                    "group": group,
                }
            )
            added += 1
        group_name = {
            "cn_myth_legend": "中国神话传说（公版情节核，句子新写）",
            "cn_fable_story": "中国寓言史传（公版情节核，句子新写）",
            "foreign": "国外寓言童话（公版情节核，句子新写）",
        }[group]
        md = (
            f"# {sid} {title}\n"
            f"系列：光光睡前小故事\n"
            f"年龄：13-15岁\n"
            f"来源：{group_name}\n"
            f"估时：约8分钟\n\n"
            f"{body}\n"
        )
        (MD_DIR / f"{sid}-{title}.md").write_text(md, encoding="utf-8")
    doc["updatedAt"] = "2026-10-18"
    doc["version"] = int(doc.get("version") or 1) + 1
    CATALOG.write_text(
        json.dumps(doc, ensure_ascii=False, separators=(",", ":")),
        encoding="utf-8",
    )
    print("new", added, "version", doc["version"])


if __name__ == "__main__":
    main()
