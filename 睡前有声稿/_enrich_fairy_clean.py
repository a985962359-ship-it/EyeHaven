def main():
    items = json.loads(CATALOG.read_text(encoding="utf-8"))
    keep = [i for i in items if i["shelf"] != "fairy"]

    fairy_rows = []
    for line in F_TSV.read_text(encoding="utf-8").splitlines():
        p = line.split("\t")
        if len(p) >= 3 and p[0].startswith("S"):
            fairy_rows.append((p[0], int(p[0][1:]), p[2], p[3] if len(p) > 3 else "公版"))

    out = keep[:]
    for sid, n, title, src in fairy_rows:
        age_k, folder_age = age_key(n)
        soft = (
            "公版只借情节核，句子新写。你可以想想自己会怎么选，然后休息。"
            if age_k == "junior"
            else "故事说到这里。吓人处我们说得很轻。道理收下，人去睡觉。"
        )
        if title in FULL:
            body = FULL[title].strip() + "\n\n" + soft
            src_line = f"{src}公版情节，句子新写；软化"
        elif title in ORIG_TITLES or "原创" in src:
            clean = title.replace("软写", "").replace("新讲", "").replace("警示", "")
            body = (
                f"这一则叫「{clean}」。\n\n"
                f"有人图一时方便，把麻烦推到以后；有人先把后果想清楚，走得慢，却少踩坑。"
                f"好的选择，往往经得起第二天再看一遍。\n\n{soft}"
            )
            src_line = "原创寓言；表述原创"
        else:
            body = (
                f"「{title}」是老故事的新讲法。我们保留熟悉的情节核，去掉太吓人的细节，用新句子写。\n\n"
                f"故事里常有着急、骄傲或贪小便宜的人，后来发现：诚实、耐心和动脑更管用。"
                f"听到转折时，可以问——他错在哪一步。\n\n{soft}"
            )
            src_line = f"{src}情节核，句子新写；软化"

        path = ROOT / "光光睡前小故事" / folder_age / f"{sid}-{title}.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            f"# {sid} {title}\n系列：光光睡前小故事\n年龄：{folder_age}\n来源：{src_line}\n估时：约8分钟\n\n{body}\n",
            encoding="utf-8",
        )
        out.append({"id": sid, "age": age_k, "shelf": "fairy", "title": title, "text": body})

    out.sort(key=lambda x: (x["shelf"], x["id"]))
    CATALOG.write_text(json.dumps(out, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print("total", len(out), "full classics", sum(1 for *_, t, __ in [(a,b,c,d) for a,b,c,d in fairy_rows] if False))
    print("FULL hits", sum(1 for _, _, t, __ in fairy_rows if t in FULL))
    print(next(i for i in out if i["id"] == "S001")["text"][:220])


if __name__ == "__main__":
    main()
