    var id: String
    var title: String
    var text: String

    /// Slow speech plus long paragraph rests is closer to 90 Chinese characters a minute.
    var minutes: Int {
        max(1, text.count / 90)
    }

    var paragraphs: [String] {
        text.components(separatedBy: "\n")
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty }
    }
}

