/// 睡前故事文案。不要接到休息计时、朗读或通知。
enum BedtimeAge: String, CaseIterable, Identifiable {
    case little = "3-5岁"
    case middle = "6-8岁"
    case older = "9-16岁"

    var id: String { rawValue }

    var hint: String {
        switch self {
        case .little: "一则一个为什么，句子短，像一本很小的百科。"
        case .middle: "讲清楚，能去学校说。像课外书，一次只翻一页。"
        case .older: "把课本没写完的那句补上。小学高年级到初中都能看。"
        }
    }
}

struct BedtimeStory: Identifiable, Hashable {
